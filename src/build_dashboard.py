"""
Computes the handful of figures the dashboard shows and writes them to
docs/data.js. Same definitions as sql/metrics.sql (M1, M3, M5, M7).

Run:  python src/build_dashboard.py
"""
import json
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
D = ROOT / "data"

par = pd.read_csv(D / "provider_directory.csv")
dis = pd.read_csv(D / "discharge_plans.csv", parse_dates=["original_planned_date", "current_discharge_date"])
ref = pd.read_csv(D / "outbound_referrals.csv", parse_dates=["sent_at", "first_response_at"])
meta = json.loads((D / "meta.json").read_text())

PARTNER_REASONS = ["Awaiting partner acceptance", "Awaiting DME delivery", "No partner accepted"]

# referrals: hours from sending to the partner's first reply (accept or decline)
r = ref.merge(par[["partner_id", "on_exacare"]], on="partner_id")
r["hours"] = (r.first_response_at - r.sent_at).dt.total_seconds() / 3600


def window(t):
    day = "Friday" if t.weekday() == 4 else "Mon–Thu"
    return f"{day}, {'afternoon' if t.hour >= 12 else 'morning'}"


r["window"] = r.sent_at.map(window)

# completed discharges: days between the first planned and the actual date
d = dis[dis.status == "Discharged"].copy()
d["days_moved"] = (d.current_discharge_date - d.original_planned_date).dt.days
bed_days = int(d.days_moved.sum())
partner_days = int(d.loc[d.primary_delay_reason.isin(PARTNER_REASONS), "days_moved"].sum())

out = dict(
    weeks=meta["weeks"],
    buildings=int(dis.facility_id.nunique()),
    bed_days=bed_days,
    partner_share=round(partner_days / bed_days, 2),
    median_hours=round(float(r.hours.median()), 1),
    by_window=[dict(label=w, hours=round(float(r.loc[r.window == w, "hours"].median()), 1))
               for w in ["Mon–Thu, morning", "Mon–Thu, afternoon", "Friday, morning", "Friday, afternoon"]],
    by_channel=[dict(label=label, hours=round(float(r.loc[r.on_exacare == on, "hours"].median()), 1))
                for label, on in [("On exacare", True), ("Email link, not on exacare", False)]],
)

target = ROOT / "docs" / "data.js"
target.write_text("// Generated by src/build_dashboard.py from data/*.csv. Synthetic data.\n"
                  "window.DASH = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
print(json.dumps(out, ensure_ascii=False))
